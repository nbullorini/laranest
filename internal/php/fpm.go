package php

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
)

const fpmTemplate = `; Generated by Laranest — do not edit, it is rewritten on every start.
[global]
pid = %[1]s/fpm.pid
%[4]sdaemonize = no
log_level = warning

[app]
listen = %[2]s
listen.mode = 0600
pm = ondemand
pm.max_children = 10
pm.process_idle_timeout = 60s
catch_workers_output = yes
%[3]sclear_env = yes
env[PATH] = $PATH
php_admin_value[error_log] = %[5]s
`

// WriteFPMConfig writes an unprivileged FPM config for one app into dir,
// listening on socket, and returns the config path.
func WriteFPMConfig(dir, socket, version string) (string, error) {
	extra := ""
	if !versionLess(version, "7.3") {
		extra = "decorate_workers_output = no\n" // directive added in PHP 7.3
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(socket), 0o700); err != nil {
		return "", err
	}
	// Linux: journald attributes syslog messages to the unit by cgroup. macOS:
	// Laranest's supervisor reads the process's output (no /proc there).
	global, workers := "; journald attributes syslog messages to the unit by cgroup\nerror_log = syslog\nsyslog.ident = php-fpm\n", "/proc/self/fd/2"
	if runtime.GOOS == "darwin" {
		global, workers = "error_log = /dev/stderr\n", "/dev/stderr"
	}
	conf := filepath.Join(dir, "fpm.conf")
	return conf, os.WriteFile(conf, []byte(fmt.Sprintf(fpmTemplate, dir, socket, extra, global, workers)), 0o644)
}
